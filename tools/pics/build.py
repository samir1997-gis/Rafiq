"""Builds the word pictures (#332): pics/<id>.svg for every word in words.py, and pics.js, which lists the words that have one.
   python3 tools/pics/build.py            writes them
   python3 tools/pics/build.py --sheets   also renders contact sheets (one per unit) to check them by eye
   (add --still to draw them at rest, as people who turn off motion see them)"""
import json, os, re, subprocess, sys, xml.etree.ElementTree as ET
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE)); sys.path.insert(0, HERE)
from kit import svg
from words import W

def vocab():
    src = open(os.path.join(ROOT, "vocab-data.js"), encoding="utf-8").read()
    js = "const fs=require('fs');" + "console.log(JSON.stringify(eval(fs.readFileSync(0,'utf8').match(/\\[[\\s\\S]*\\]/)[0])))"
    return json.loads(subprocess.run(["node", "-e", js], input=src, capture_output=True, text=True, check=True).stdout)

def main():
    words = {w["id"]: w for w in vocab()}
    out = os.path.join(ROOT, "pics"); os.makedirs(out, exist_ok=True)
    bad = [i for i in W if i not in words]
    if bad: sys.exit(f"ids not in vocab-data.js: {bad}")
    for f in os.listdir(out):
        if f.endswith(".svg") and int(f[:-4]) not in W: os.remove(os.path.join(out, f))
    for i, (bg, draw) in sorted(W.items()):
        s = svg(draw(), bg)
        ET.fromstring(s)   # fails loudly on a malformed picture
        open(os.path.join(out, f"{i}.svg"), "w", encoding="utf-8").write(s)
    ids = sorted(W)
    # words that share one drawing (to pray / prayer): a "tap the picture" question never offers two of them (#358)
    same, twin = {}, {}
    for i in ids: same.setdefault(open(os.path.join(out, f"{i}.svg"), encoding="utf-8").read(), []).append(i)
    for k, g in enumerate(v for v in same.values() if len(v) > 1):
        for i in g: twin[i] = k
    open(os.path.join(ROOT, "pics.js"), "w", encoding="utf-8").write(
        "// Generated by tools/pics/build.py (#332): the words that have a picture in pics/<id>.svg. Don't edit by hand.\n"
        f"const PICS = new Set({json.dumps(ids, separators=(',', ':'))});\n"
        "// A word's picture as an <img>, or '' when it has none. v= busts the cache when the drawings change.\n"
        "function wordPic(id, cls) { return PICS.has(+id) ? `<img class=\"${cls || 'wpic'}\" src=\"pics/${id}.svg?v=1\" alt=\"\" loading=\"lazy\" decoding=\"async\">` : ''; }\n"
        "// Two words drawn with the very same picture (word id → its group).\n"
        f"const PIC_TWIN = {json.dumps(twin, separators=(',', ':'))};\n"
        "function samePic(a, b) { return +a === +b || (PIC_TWIN[a] !== undefined && PIC_TWIN[a] === PIC_TWIN[b]); }\n")
    print(f"{len(ids)} of {len(words)} words have a picture; {sum(os.path.getsize(os.path.join(out, f'{i}.svg')) for i in ids) // 1024} KB")
    if "--sheets" in sys.argv: sheets(words)

def sheets(words):
    """One PNG per unit, the SVGs drawn inline so --still can stop the motion; also lists any picture that spills off its tile."""
    from playwright.sync_api import sync_playwright
    i = sys.argv.index("--sheets"); dest = sys.argv[i + 1] if len(sys.argv) > i + 1 and not sys.argv[i + 1].startswith("--") else os.path.join(HERE, "sheets")
    os.makedirs(dest, exist_ok=True)
    units = {}
    for k in sorted(W): units.setdefault(words[k]["unit"], []).append(k)
    still = "*{animation:none!important}" if "--still" in sys.argv else ""
    spill = []
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path=os.environ.get("CHROME") or None); pg = b.new_page(viewport={"width": 1400, "height": 900})
        for u, ids in units.items():
            cells = "".join(f'<figure data-id="{k}">{open(os.path.join(ROOT, "pics", f"{k}.svg"), encoding="utf-8").read()}<figcaption>{k} · {words[k]["en"][:34]}</figcaption></figure>' for k in ids)
            pg.set_content("<style>body{margin:16px;font:13px Arial;background:#fafafa}h1{font-size:18px}div{display:grid;grid-template-columns:repeat(8,1fr);gap:10px}"
                           f"figure{{margin:0;text-align:center}}svg{{width:150px;height:150px}}figcaption{{height:30px}}{still}</style><h1>{u} — {len(ids)} pictures</h1><div>{cells}</div>")
            pg.wait_for_timeout(700)
            spill += pg.evaluate("""[...document.querySelectorAll('figure')].map(f => { const g = f.querySelector('g.c'); if (g.hasAttribute('clip-path')) return null; const b = g.getBBox();
                return (b.x < -1 || b.y < -1 || b.x + b.width > 201 || b.y + b.height > 201) ? f.dataset.id : null }).filter(Boolean)""")
            pg.screenshot(path=os.path.join(dest, re.sub(r"[^a-z0-9]+", "-", u.lower()).strip("-") + ".png"), full_page=True)
        b.close()
    print("sheets in", dest, "| spill off the tile:", ", ".join(spill) or "none")

if __name__ == "__main__": main()
